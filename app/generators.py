def generate_llms_txt(
    site_title: str,
    summary: str,
    sections: Optional[List[Dict[str, Any]]] = None,
    optional_links: Optional[List[Dict[str, str]]] = None
) -> str:
    """Generate a clean, standardized /llms.txt file."""
    lines = []
    lines.append(f"# {site_title.strip() or 'Project / Website Name'}\n")
    
    if summary:
        lines.append(f"> {summary.strip()}\n")
    else:
        lines.append("> Comprehensive documentation, products, and knowledge resources for users and AI assistants.\n")
        
    lines.append("## Core Information\n")
    
    if sections:
        for s in sections:
            title = s.get("title", "Resource")
            url = s.get("url", "/")
            desc = s.get("description", "")
            if desc:
                lines.append(f"- [{title}]({url}): {desc}")
            else:
                lines.append(f"- [{title}]({url})")
    else:
        lines.append("- [Home Page](/): Main overview and core offerings")
        lines.append("- [About Us](/about): Company background, mission, and team")
        lines.append("- [Documentation](/docs): Complete guides, tutorials, and references")
        lines.append("- [API Reference](/api): Direct endpoints and integration guides")
        
    if optional_links:
        lines.append("\n## Optional & External Resources\n")
        for link in optional_links:
            title = link.get("title", "Link")
            url = link.get("url", "#")
            lines.append(f"- [{title}]({url})")
            
    return "\n".join(lines) + "\n"

