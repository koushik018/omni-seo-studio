def generate_jsonld_snippet(schema_type: str, data: Dict[str, Any]) -> str:
    """Generate formatted JSON-LD <script> block for Schema.org."""
    base = {
        "@context": "https://schema.org",
        "@type": schema_type
    }
    
    if schema_type == "Organization":
        base.update({
            "name": data.get("name", "My Company"),
            "url": data.get("url", "https://example.com"),
            "logo": data.get("logo", "https://example.com/logo.png"),
            "description": data.get("description", "Company description"),
            "sameAs": data.get("sameAs", [
                "https://twitter.com/example",
                "https://linkedin.com/company/example",
                "https://github.com/example"
            ])
        })
    elif schema_type == "FAQPage":
        faqs = data.get("faqs", [
            {"q": "What makes this tool unique?", "a": "It audits both traditional search engine crawlers and modern AI agents."},
            {"q": "Does it support llms.txt?", "a": "Yes, it fully validates and generates RFC-compliant llms.txt files."}
        ])
        base["mainEntity"] = [
            {
                "@type": "Question",
                "name": item.get("q", ""),
                "acceptedAnswer": {
                    "@type": "Answer",
                    "text": item.get("a", "")
                }
            }
            for item in faqs
        ]
    elif schema_type == "Article":
        base.update({
            "headline": data.get("headline", "Article Headline"),
            "description": data.get("description", "Summary of the article"),
            "image": data.get("image", "https://example.com/cover.jpg"),
            "author": {
                "@type": "Person",
                "name": data.get("author_name", "Author Name")
            },
            "publisher": {
                "@type": "Organization",
                "name": data.get("publisher_name", "Publisher Name"),
                "logo": {
                    "@type": "ImageObject",
                    "url": data.get("publisher_logo", "https://example.com/logo.png")
                }
            },
            "datePublished": data.get("datePublished", "2026-01-01T08:00:00+00:00"),
            "dateModified": data.get("dateModified", "2026-01-01T09:00:00+00:00")
        })
    elif schema_type == "WebSite":
        base.update({
            "name": data.get("name", "Site Name"),
            "url": data.get("url", "https://example.com"),
            "potentialAction": {
                "@type": "SearchAction",
                "target": f"{data.get('url', 'https://example.com')}/search?q={{search_term_string}}",
                "query-input": "required name=search_term_string"
            }
        })
    else:
        base.update(data)
        
    formatted_json = json.dumps(base, indent=2)
    return f'<script type="application/ld+json">\n{formatted_json}\n</script>'

def generate_meta_snippet(data: Dict[str, str]) -> str:
    """Generate clean HTML <head> meta tag block."""
    title = data.get("title", "")
    desc = data.get("description", "")
    canonical = data.get("canonical", "")
    og_image = data.get("og_image", "")
    site_name = data.get("site_name", "")
    
    tags = [
        "<!-- Primary Meta Tags -->",
        f"<title>{title}</title>",
        f'<meta name="title" content="{title}">',
        f'<meta name="description" content="{desc}">',
        '<meta name="viewport" content="width=device-width, initial-scale=1.0">',
        '<meta charset="UTF-8">',
        ""
    ]
    
    if canonical:
        tags.append(f'<link rel="canonical" href="{canonical}">')
        tags.append("")
        
    tags.extend([
        "<!-- Open Graph / Facebook / LinkedIn -->",
        f'<meta property="og:type" content="website">',
        f'<meta property="og:url" content="{canonical}">',
        f'<meta property="og:title" content="{title}">',
        f'<meta property="og:description" content="{desc}">'
    ])
    
    if og_image:
        tags.append(f'<meta property="og:image" content="{og_image}">')
    if site_name:
        tags.append(f'<meta property="og:site_name" content="{site_name}">')
        
    tags.extend([
        "",
        "<!-- Twitter / X -->",
        '<meta name="twitter:card" content="summary_large_image">',
        f'<meta name="twitter:url" content="{canonical}">',
        f'<meta name="twitter:title" content="{title}">',
        f'<meta name="twitter:description" content="{desc}">'
    ])
    
    if og_image:
        tags.append(f'<meta name="twitter:image" content="{og_image}">')
        
    return "\n".join(tags) + "\n"

def generate_noscript_block(title: str, description: str, headings: Optional[List[str]] = None, links: Optional[List[Dict[str, str]]] = None) -> str:
    """Generate a rich, semantic <noscript> fallback block for AI crawlers and non-JS engines."""
    h1 = title or "Page Overview"
    p = description or "This page requires JavaScript for interactive features, but its core content is accessible here."
    
    subheadings_html = ""
    if headings:
        subheadings_html = "\n    ".join([f"<h3>{h}</h3>" for h in headings[:4]])
        
    links_html = ""
    if links:
        links_html = "\n      ".join([f'<li><a href="{l.get("url", "#")}">{l.get("title", "Link")}</a></li>' for l in links[:5]])
    else:
        links_html = '<li><a href="/">Home</a></li>\n      <li><a href="/about">About Us</a></li>\n      <li><a href="/docs">Documentation</a></li>'

    return f"""<!-- AI Crawler Static HTML Fallback (Ensures ChatGPT, Claude & Perplexity index your content without executing JS) -->
<noscript>
  <div style="padding: 20px; font-family: sans-serif; max-width: 800px; margin: 0 auto; line-height: 1.6;">
    <h1>{h1}</h1>
    <p>{p}</p>
    {subheadings_html}
    <hr style="margin: 20px 0; border: 0; border-top: 1px solid #ccc;">
    <nav>
      <strong>Essential Navigation & Content:</strong>
      <ul>
      {links_html}
      </ul>
    </nav>
  </div>
</noscript>"""

def generate_defer_script_fix(scripts: List[str]) -> str:
    """Generate optimized, non-blocking script tags with defer/async attributes."""
    if not scripts:
        return "<!-- No render-blocking scripts detected in <head>! All scripts are clean. -->"
        
    lines = [
        "<!-- Optimized Non-Blocking Scripts (Fixes render-blocking issues above the fold) -->"
    ]
    for s in scripts:
        lines.append(f'<script defer src="{s}"></script>')
    return "\n".join(lines)

